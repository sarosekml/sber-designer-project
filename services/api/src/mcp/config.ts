import { createHash } from 'node:crypto';

import type { SberDesignerConfig } from '@sber-designer/llm-gateway';
import type { SberDesignerProject } from '@sber-designer/shared-types';

import { applyMcpServerOverrides } from './overrides';
import { redactMcpServerConfig } from './redaction';
import { isRemoteMcpServer, validateMcpServerPolicy } from './security';
import type {
  McpDiagnostic,
  McpFrontendSummary,
  McpSecurityOptions,
  McpToolSummary,
  NormalizedMcpServer,
  NormalizedMcpTransport,
  McpServerEntry,
} from './types';

export { redactMcpServerConfig } from './redaction';

export interface McpSummaryOptions extends McpSecurityOptions {
  project?: SberDesignerProject | null;
  runtimeStatuses?: Record<
    string,
    Partial<McpFrontendSummary['servers'][number]['status']> | undefined
  >;
  tools?: Record<string, McpToolSummary[] | undefined>;
}

export function normalizeMcpServers(
  cfg: SberDesignerConfig,
  _options: McpSecurityOptions = {},
): NormalizedMcpServer[] {
  const namespaces = new Map<string, string>();
  const servers: NormalizedMcpServer[] = [];

  for (const [key, entry] of Object.entries(cfg.mcpServers)) {
    const namespace = normalizeMcpNamespace(key);
    const previous = namespaces.get(namespace);
    if (previous) {
      throw new Error(
        `Duplicate MCP namespace "${namespace}" generated by "${previous}" and "${key}".`,
      );
    }
    namespaces.set(namespace, key);
    servers.push({
      key,
      namespace,
      transport: normalizeTransport(entry),
      enabled: entry.enabled !== false,
      configEnabled: entry.enabled !== false,
      runtimeEnabled: true,
      ...(entry.description ? { description: entry.description } : {}),
      entry,
      configHash: computeMcpConfigHash(entry),
    });
  }

  return servers;
}

export function normalizeMcpNamespace(key: string): string {
  const normalized = key
    .trim()
    .replace(/[^A-Za-z0-9_]+/gu, '_')
    .replace(/^_+|_+$/gu, '')
    .toLowerCase();
  const safe = normalized || 'mcp';
  return /^[A-Za-z_]/u.test(safe) ? safe : `mcp_${safe}`;
}

export function normalizeTransport(entry: McpServerEntry): NormalizedMcpTransport {
  return entry.type === 'stdio' ? 'stdio' : 'streamable-http';
}

export function computeMcpConfigHash(entry: McpServerEntry): string {
  const canonical = stableStringify(redactMcpServerConfig(entry));
  return `sha256:${createHash('sha256').update(canonical).digest('hex')}`;
}

export function summarizeMcpServersForFrontend(
  cfg: SberDesignerConfig,
  options: McpSummaryOptions = {},
): McpFrontendSummary {
  const diagnostics: McpDiagnostic[] = [];
  const normalized = applyMcpServerOverrides(normalizeMcpServers(cfg, options), options.project);
  const servers = normalized.map((server) => {
    const security = validateMcpServerPolicy(server, options);
    const serverDiagnostics = [...security.diagnostics];
    diagnostics.push(...serverDiagnostics);
    const runtimeStatus = options.runtimeStatuses?.[server.key] ?? {};
    const tools = options.tools?.[server.key] ?? [];
    const selectedToolCount = tools.filter((tool) => tool.enabled).length;
    const transport = server.enabled ? (runtimeStatus.transport ?? 'not_connected') : 'disabled';
    return {
      key: server.key,
      namespace: server.namespace,
      transport: server.transport,
      enabled: server.enabled,
      configEnabled: server.configEnabled,
      runtimeEnabled: server.runtimeEnabled,
      remote: isRemoteMcpServer(server),
      ...(server.description ? { description: server.description } : {}),
      configHash: server.configHash,
      status: {
        transport,
        upstream: runtimeStatus.upstream ?? ('n/a' as const),
        toolsReady: Boolean(
          runtimeStatus.toolsReady ?? (transport === 'connected' && tools.length > 0),
        ),
        ...(runtimeStatus.lastConnectedAt
          ? { lastConnectedAt: runtimeStatus.lastConnectedAt }
          : {}),
        ...(runtimeStatus.lastError ? { lastError: runtimeStatus.lastError } : {}),
      },
      toolCount: selectedToolCount,
      selectionMode:
        server.toolSelection || server.toolOverrides ? ('explicit' as const) : ('auto' as const),
      selectionLimit: 64,
      selectedToolCount,
      discoveredToolCount: tools.length,
      tools,
      config: redactMcpServerConfig(server.entry),
      diagnostics: serverDiagnostics,
    };
  });

  return { servers, diagnostics };
}

function stableStringify(value: unknown): string {
  return JSON.stringify(sortJson(value));
}

function sortJson(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortJson);
  if (!value || typeof value !== 'object') return value;
  const record = value as Record<string, unknown>;
  const sorted: Record<string, unknown> = {};
  for (const key of Object.keys(record).sort()) {
    sorted[key] = sortJson(record[key]);
  }
  return sorted;
}
