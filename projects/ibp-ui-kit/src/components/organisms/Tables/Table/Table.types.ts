import { TableRowDetail } from '@devexpress/dx-react-grid-material-ui';

import { SearchRequestDto } from '@sber-ibp/core';

import { TableStylesType } from '@/components/organisms/Tables/Table';

import { RowsConfig } from './TableProps/TableRow.types';
import {
  ColumnName,
  ColumnsConfig,
  ColumnsState,
  PagingProp,
  ResizingProp,
  Row,
  RowProps,
  TableConfigProp,
  TableMessages,
} from './TableProps';
import { ScrollState, TableState, UiState } from './TableState';

type BaseRowDetailConfig<RowType extends object> = {
  /**
   * A component that renders the detail row's content within the detail cell.
   */
  contentComponent: React.ComponentType<TableRowDetail.ContentProps>;
  /**
   * Function that determines the visibility of the expansion icon.
   */
  showToggleIcon: (row: RowType) => boolean;
};

/**
 * Main specification (sorting, filtering, pagination):
 * https://confluence.sberbank.ru/pages/viewpage.action?pageId=5170398102
 */
export interface TableProps<RowType extends object, Filter extends object> {
  /**
   * Default filters state. Previously the component worked with `filters` parameter
   */
  defaultFilters?: Filter;
  /**
   * Defines if the table is in edit mode
   */
  isEditMode?: boolean;
  /**
   * Is used to rewrite style classes
   */
  classes?: TableStylesType;
  /**
   * TestId of parent component
   */
  dataTestId: string;
  /**
   * If 'true', the loader will be shown
   */
  isLoading?: boolean;
  /**
   * Table representation config
   */
  tableConfig?: TableConfigProp;
  /**
   * Provides a custom messages for different parts of the table
   */
  messages?: Partial<TableMessages>;
  /**
   * Defines the initial state of the Table Component, but not the default one.
   * The difference is that in case the state is reset, it is reset to
   * defaults (defined in columns) not to initial state. As the initial configuration
   * this configuration has more priority under the default configuration.
   * <b>
   *  (!) Please do not use this configuration instead of columns configuration,
   *  because it's developed for providing external cache value right to the component.
   *  (!) Be careful, there is not double check for the correctness of the structure
   *  you provided here and it should be aligned with the columns configuration
   * </b>
   */
  initialState?: TableState<RowType, Filter>;
  /**
   * Table identifier which is used for caching table state in the local storage,
   * and for subscribing on controlling events (if the parameter is not provided caching is not
   * applied and controlling outside is impossible).
   * To control the table use `EventBasedTableStateController` or `useEventTrigger` hook with
   * channel id generated by `getTableEventChannelId` function from tableCode.
   */
  tableCode?: string;
  /**
   * Array of column header names and titles (labels)
   */
  columns: ColumnsConfig<RowType>;
  /**
   * Cell-render configuration which defines how to render `RowData` in the set of cells.
   * Defines how to render rows and containing cells.
   */
  rows: Row<RowType>[] | RowsConfig<RowType>;

  rowDetailConfig?: BaseRowDetailConfig<RowType>;
  /**
   * Row additional config (row action handlers and identifiers)
   */
  rowProps?: RowProps<RowType>;
  /**
   * Defines default pagination configuration
   */
  paging?: PagingProp;
  /**
   * Defines the state of the table grouping
   */
  grouping?: ColumnName<RowType>[];
  /**
   * Defines the state of the table initial scroll
   */
  scroll?: ScrollState;
  /**
   * Defines table resizing configuration parameters.
   * If the parameter is provided as object or as 'true'
   * the column resizing feature is enabled otherwise - not.
   * @default false
   */
  columnsResizing?: ResizingProp<RowType> | boolean;
  /**
   * Defines if the columns can be reordered
   */
  canReorderColumns?: boolean;
  /**
   * Defines if the columns can be dynamically hidden or shown
   */
  canChangeVisibility?: boolean;
  /**
   * Defines whether columns can be fixed
   */
  canFixColumns?: boolean;
  /**
   * Defines whether rows can be selected with a checkbox
   */
  canSelectRowsWithCheckbox?: boolean;
  /**
   * Callback which is used to get table relevant state,
   * called if the state of the component is changed
   */
  onTableStateChanged?: (
    state: TableState<RowType, Filter>,
    prevState: TableState<RowType, Filter> | undefined,
  ) => void;
  /**
   * Callback which is called in response to selectedRow/order/columnWidth/columnVisibility changes
   */
  onUiStateChanged?: (config: UiState<RowType>) => void;
  /**
   * Callback to reset table settings (column visibility and order) to default
   */
  onResetTableSettings?: () => void;
  /**
   * Callback which is called in response to table configuration change
   * (table rows refetching function)
   */
  updateData?: (config: SearchRequestDto<Filter>) => void;
  /**
   * Callback which is called in response to configuration change
   * @deprecated use configLoaderProps instead
   */
  updateColumnsConfig?: (config: ColumnsState<RowType>) => void;
  /**
   * If true, adds a thin border to outer edge of Table. Defaults to false.
   */
  isBordered?: boolean;
  /**
   * Use if you need to customize the footer of the table
   * @param stockPagingPanelContainer Allows you to get stock paging panel
   */
  customFooter?: (stockPagingPanelContainer?: React.ReactNode) => React.ReactNode;
}
